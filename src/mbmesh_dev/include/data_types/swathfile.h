CollectedPointCloud read_datalist(std::string datatlist_path) {
    CollectedPointCloud collected_point_cloud{};
    // datalist entry
    //      ↓
    // open one swath file
    //      ↓
    // read one ping into MB-System buffers
    //      ↓
    // convert each valid beam directly to CollectedPoint
    //      ↓
    // reuse buffers for next ping
    //      ↓
    // close file and continue
    return collected_point_cloud;
}
